interface Props {
  params: Promise<{ slug: string }>
}

// Replaces the entire ADR 0011/0012 meta-tag-injection mechanism — the
// server genuinely renders this page per Post, so Next's generateMetadata
// can just read the same data. See docs/adr/0013.
export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { slug } = await params
  const post = await blogApi.getPost(slug, { cache: 'no-store' }).catch(() => null)
  if (!post) return {}

  const canonical = blogPostUrl(post.slug)
  const images = post.coverImageUrl ? [{ url: post.coverImageUrl, alt: post.title }] : undefined

  return {
    title: post.title,
    description: post.excerpt,
    alternates: { canonical },
    openGraph: {
      type: 'article',
      url: canonical,
      title: post.title,
      description: post.excerpt,
      siteName: SITE_TITLE,
      images,
      publishedTime: post.publishedAt ?? undefined,
      modifiedTime: post.updatedAt,
      authors: [SITE_ORIGIN],
    },
    twitter: {
      card: post.coverImageUrl ? 'summary_large_image' : 'summary',
      title: post.title,
      description: post.excerpt,
      images,
    },
  }
}

const backLinkClass = 'self-start text-sm no-underline'

// Below ~720px the aside and the article stack, and the aside stops being sticky.
const asideClass = 'flex flex-[1_1_200px] flex-col gap-5 self-start sticky top-24 max-[720px]:static'
const rowClass = 'flex flex-wrap gap-x-12 gap-y-6 border-t border-(--ind-divider)'

export default async function BlogPostPage({ params }: Props) {
  const { slug } = await params

  // Next memoizes identical fetch() calls within one render pass, so this
  // doesn't double-hit the API even though generateMetadata above already
  // fetched the same URL — verified in Phase 3's manual testing.
  const backToBlog = await blogListPath()

  let post
  try {
    post = await blogApi.getPost(slug, { cache: 'no-store' })
  } catch (err) {
    if (err instanceof ApiError && err.status === 404) notFound()
    return (
      <div className="flex flex-col gap-8 pt-[clamp(32px,5vw,56px)] pb-22">
        <Link href={backToBlog} className={backLinkClass}>
          ← Back to Blog
        </Link>
        <p className="m-0 text-base opacity-70">Could not load this post right now. Please try again later.</p>
      </div>
    )
  }

  const comments = await blogApi.listComments(slug, { cache: 'no-store' })
  const sanitizedContent = stripRawHtmlTags(post.content)
  const canonical = blogPostUrl(post.slug)

  return (
    <article className="flex flex-col gap-8 pt-[clamp(32px,5vw,56px)]">
      <JsonLd
        data={{
          '@context': 'https://schema.org',
          '@type': 'BlogPosting',
          headline: post.title,
          description: post.excerpt,
          url: canonical,
          mainEntityOfPage: canonical,
          ...(post.coverImageUrl && { image: post.coverImageUrl }),
          ...(post.publishedAt && { datePublished: post.publishedAt }),
          dateModified: post.updatedAt,
          author: { '@type': 'Person', '@id': PERSON_ID, name: 'Alison Rafael Marinho Gonçalves', url: SITE_ORIGIN },
        }}
      />
      <ViewRegistrar slug={post.slug} />
      <LiveCursorOverlay room={`post:${post.slug}`} key={post.slug} />

      <Link href={backToBlog} className={backLinkClass}>
        ← Back to Blog
      </Link>

      <header className="flex max-w-[900px] flex-col gap-4">
        <p className="ind-label m-0">
          {post.publishedAt && `${formatDate(post.publishedAt)} / `}
          {post.viewCount.toLocaleString('en-US')} views
        </p>
        <h1 className="text-[clamp(40px,6vw,72px)] leading-[0.95] break-words text-pretty">{post.title}</h1>
        <p className="m-0 max-w-[64ch] text-xl leading-normal text-pretty opacity-80">{post.excerpt}</p>
      </header>

      {post.coverImageUrl && <CoverImage src={post.coverImageUrl} alt={post.title} />}

      <div className={`${rowClass} pt-14 pb-18`}>
        <aside className={asideClass}>
          <p className="ind-label m-0">01 / Article</p>
          <ShareButtons slug={post.slug} title={post.title} />
        </aside>
        <div className="flex min-w-0 max-w-[72ch] flex-[3_1_480px] flex-col gap-5 text-lg leading-[1.7]">
          <Markdown components={markdownComponents}>{sanitizedContent}</Markdown>
        </div>
      </div>

      <section id="comments" className={`${rowClass} scroll-mt-16 pt-14 pb-22`}>
        <div className="flex flex-[1_1_200px] flex-col gap-2">
          <p className="ind-label m-0">02 / Discussion</p>
          <h2 className="text-[clamp(36px,4.5vw,52px)] leading-none">Comments.</h2>
        </div>
        <Comments slug={post.slug} initialComments={comments} />
      </section>
    </article>
  )
}
